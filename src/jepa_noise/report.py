def _fmt(value, digits=3):
    return f"{value:.{digits}f}" if isinstance(value, (int, float)) else "none"


def _prediction_summary(identifier: str, detail: dict) -> str:
    if "clauses" in detail:
        e1a = detail["clauses"]["e1a"]
        e1b = detail["clauses"]["e1b"].get("detail") or {}
        base = _prediction_summary(identifier, e1a)
        if identifier == "R1":
            return (base + "; E1b channel clean-cell median "
                    f"{_fmt(e1b.get('clean_cell_median_angle_deg'))} deg "
                    "(<=10)")
        if identifier == "R2":
            return (base + "; E1b channel Spearman "
                    f"{_fmt(e1b.get('spearman'))} (>=0.8), seed-mean angle at "
                    f"g=.05 {_fmt(e1b.get('seed_mean_angle_at_g0p05_deg'))} deg "
                    "(>=45)")
    if identifier == "R1":
        cells = detail.get("cells", {})
        passed = sum(1 for cell in cells.values() if cell.get("pass"))
        medians = [cell["median_max_angle_deg"] for cell in cells.values()
                   if cell.get("median_max_angle_deg") is not None]
        maximum = f"{max(medians):.3f} deg" if medians else "none"
        return (f"cells {passed}/{len(cells)} pass; max cell median angle "
                f"{maximum}")
    if identifier == "R2":
        cells = detail.get("cells", {})
        passed = sum(1 for cell in cells.values() if cell.get("spearman_pass"))
        required = [cell["required_median_at_gamma1_deg"]
                    for cell in cells.values()
                    if cell.get("required_median_at_gamma1_deg") is not None]
        required_text = (f"{required[0]:.3f} deg" if required else "none")
        return (f"scale cells with Spearman>=0.8: {passed}/{len(cells)}; "
                f"required cell median {required_text}")
    if identifier == "R3":
        maximum = detail.get("max_spectrum_difference")
        return (f"max spectrum difference {maximum:.3e}" if maximum is not None
                else "no rows")
    if identifier == "R3b":
        cells = detail.get("cells", {})
        eligible = [key for key, value in cells.items() if value.get("eligible")]
        passed = sum(1 for key in eligible if cells[key].get("pass"))
        return (f"eligible cells {len(eligible)}; pass {passed}; "
                f"annihilation control rank-ineligible (outside primary grid)")
    if identifier == "R4a":
        cells = detail.get("cells", {})
        passed = sum(1 for cell in cells.values() if cell.get("pass"))
        return f"cells {passed}/{len(cells)} pass"
    if identifier == "R4b":
        cells = detail.get("cells", {})
        passed = sum(1 for cell in cells.values() if cell.get("pass_beta_10"))
        return f"cells {passed}/{len(cells)} pass at beta=10; beta=0.1/1 in table"
    if identifier == "R5":
        cells = detail.get("cells", {})
        parts = [f"{key}: {value['wins']}/{value['evaluable_seeds']} wins"
                 for key, value in cells.items()]
        return "; ".join(parts) if parts else "no E1c rows"
    return "stored tables"


def render(rows: list[dict]) -> str:
    lines = ['# JEPA v3 prediction status', '',
             'Development output; no prospective grid evidence yet. Analytic fixtures and the disclosed toy are reported separately.', '',
             '| Prediction | Campaign | Status | Reason | Evaluation seeds | Numeric evidence |',
             '|---|---|---|---|---|---|']
    seen = set()
    for row in rows:
        if row['id'] in seen or row['status'] not in {'pass', 'fail', 'not_evaluable', 'not_run'}:
            raise ValueError('invalid_prediction_record')
        seen.add(row['id'])
        if row['status'] in {'pass', 'fail'} and not row.get('evidence'):
            raise ValueError('empirical_outcome_requires_evidence')
        cells = [row['id'], row['campaign'], row['status'],
                 row.get('reason') or 'none',
                 ', '.join(map(str, row.get('seeds') or [])) or 'none',
                 row.get('evidence') or 'none']
        # Markdown table cells cannot contain a raw pipe or a newline; escape
        # pipes and collapse newlines rather than aborting the whole report
        # (a status file edited by hand must never break regeneration).
        cells = [
            str(x).replace('|', '\\|').replace('\n', ' ') for x in cells
        ]
        lines.append('| ' + ' | '.join(cells) + ' |')
    return '\n'.join(lines) + '\n'


def write_aggregates(aggregates: dict, root: Path) -> None:
    for campaign, payload in aggregates.items():
        directory = runner.campaign_root(root, campaign)
        directory.mkdir(parents=True, exist_ok=True)
        runner.atomic_write_json(directory / f"aggregate_{campaign}.json", payload)


def build_text(root: Path, config_path: Path) -> tuple[str, dict]:
    rows, aggregates = build_predictions(root, config_path)
    return render(rows), aggregates


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("campaign", choices=["all", "E1", "E2", "E3", "E4"])
    parser.add_argument("--root", type=Path, default=runner.ROOT)
    parser.add_argument("--config", type=Path, default=runner.DEFAULT_CONFIG)
    parser.add_argument("--check", action="store_true",
                        help="compare the regenerated file with the one on disk")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    directory = root / "docs" / "jepa"
    text, aggregates = build_text(root, args.config.resolve())
    if aggregates:
        write_aggregates(aggregates, root)
    if args.campaign in ("all", "E1"):
        rows_text = text
        output = directory / "PREDICTIONS.md"
    else:
        status = json.loads((directory / "PREDICTION_STATUS.json").read_text(
            encoding="utf-8"))
        filtered = [row for row in status["predictions"]
                    if row["campaign"] == args.campaign]
        rows_text = render(filtered)
        output = directory / f"PREDICTIONS_{args.campaign}.md"
    if args.check:
        current = output.read_text(encoding="utf-8") if output.exists() else None
        if current == rows_text:
            print(f"OK byte-identical: {output}")
            return 0
        print(f"MISMATCH: {output}")
        return 1
    output.write_text(rows_text, encoding="utf-8")
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
