"""Deterministic E1 prediction-status renderer for docs/jepa/PREDICTIONS.md.

``python -m jepa_noise.report E1`` regenerates ``docs/jepa/PREDICTIONS.md`` from
the stored E1 row tables (write-once JSON rows under
``results/jepa/20261017_wp3_e1*/attempt_*/rows/``).  ``all`` delegates to the
same code path, so the two invocations are byte-identical while only E1 has
empirical tables.  Rows for campaigns without stored tables come from
``docs/jepa/PREDICTION_STATUS.json`` unchanged.

The renderer is a pure function of the stored tables: no timestamps, no set
iteration order, no attempt-specific paths, and fixed numeric formatting.  This
is the v3 WP3 acceptance requirement "PREDICTIONS.md for R1-R5 regenerated by
python -m jepa_noise.report E1" (runbook v4 Sec.8, WP3).
"""
from __future__ import annotations

import argparse
import json
import math
import statistics
from pathlib import Path

from . import run as runner

R1_MAX_MEDIAN_ANGLE_DEG = 5.0
R2_SPEARMAN_MIN = 0.8
R2_REQUIRED_ANGLE_DEG = 45.0
R2_REQUIRED_CELL = (0.4, 3.0)
R3_MAX_SPECTRUM_DIFFERENCE = 1e-8
R3B_POPULATION_RECOVERY_RAD = 1e-6
R3B_MAX_MEDIAN_ANGLE_DEG = 5.0
R4_POPULATION_RECOVERY_RAD = 1e-6
R4_MAX_MEDIAN_ANGLE_DEG = 5.0
R5_MIN_WINS = 4

ANGLED = ["r1_cca", "r5_gevp", "r6_finite_beta_0.1", "r7_finite_beta_1",
          "r8_finite_beta_10", "r9_oracle"]


def _evidence_path(root: Path, path: Path) -> str:
    try:
        return str(path.relative_to(root)).replace("\\", "/")
    except ValueError:  # pragma: no cover - root is the repository root
        return path.name


def _index(records: dict[str, dict], campaign: str) -> dict[tuple[str, int], dict]:
    index: dict[tuple[str, int], dict] = {}
    for record in records.values():
        if record.get("campaign") != campaign:
            continue
        cell = record.get("cell")
        identifier = json.dumps(cell, sort_keys=True, separators=(",", ":"))
        index[(identifier, int(record.get("seed", -1)))] = record
    return index


def _get(index, cell: dict, seed: int):
    key = (json.dumps(cell, sort_keys=True, separators=(",", ":")), int(seed))
    return index.get(key)


def _method_angle(record: dict, method: str) -> float | None:
    entry = (record.get("methods") or {}).get(method)
    if not entry or entry.get("status") != "evaluated":
        return None
    angles = entry.get("angles") or {}
    value = angles.get("max_angle_deg")
    return float(value) if value is not None else None


def _median(values: list[float]) -> float | None:
    return float(statistics.median(values)) if values else None


def _e1a_angle_cells(config: dict) -> list[dict]:
    spec = config["E1a"]
    cells = []
    for theta in spec["theta_scale"]:
        for eta in spec["eta_scale"]:
            for gamma in spec["gamma_load"]:
                cells.append({"theta_scale": theta, "eta_scale": eta,
                              "gamma_load": gamma, "n": spec["angle_n"]})
    return cells


def _e1a_scale_cells(config: dict) -> list[tuple[float, float]]:
    spec = config["E1a"]
    return [(theta, eta) for theta in spec["theta_scale"]
            for eta in spec["eta_scale"]]


def _spearman(x, y) -> float | None:
    from scipy.stats import spearmanr

    if len(set(x)) < 2 or len(set(y)) < 2:
        return None
    value = float(spearmanr(x, y).statistic)
    return None if not math.isfinite(value) else value


def _e1b_primary(record: dict, method: str = "r1_cca"):
    split = (record.get("splits") or {}).get("channel") or {}
    entry = (split.get("methods") or {}).get(method) or {}
    if entry.get("status") != "evaluated" or not entry.get("angles"):
        return None
    return float(entry["angles"]["max_angle_deg"])


def _e1b_clause_rows(config: dict, records: dict):
    """Per common-mode cell (line=0) channel-split CCA angles by seed."""
    spec = config["E1b"]
    index = _index(records, "E1b")
    target_cell = next((cell for cell in spec["cells"]
                        if cell["cell_id"] == "g0_line0"), None)
    per_g = {}
    for cell in spec["cells"]:
        if cell["line_multiplier"] != 0.0:
            continue
        angles = []
        for seed in spec["seeds"]:
            record = _get(index, {
                "cell_id": cell["cell_id"],
                "common_strength": cell["common_strength"],
                "line_multiplier": cell["line_multiplier"]}, seed)
            angle = _e1b_primary(record) if record else None
            if angle is not None:
                angles.append(angle)
        per_g[cell["cell_id"]] = {
            "g": cell["common_strength"],
            "seed_angles_deg": angles,
            "seeds_recorded": len(angles),
            "expected_seeds": len(spec["seeds"]),
            "seeds_complete": len(angles) == len(spec["seeds"]),
            "seed_mean_angle_deg": float(sum(angles) / len(angles))
            if angles else None,
            "median_angle_deg": _median(angles),
        }
    reference = None
    if target_cell is not None:
        reference = per_g.get(target_cell["cell_id"])
    return per_g, reference


def _r1_e1b_clause(config: dict, records: dict) -> dict:
    if not records:
        return {"status": "not_evaluable",
                "reason": "E1b_pending_v4_R1_R2_clause", "detail": None}
    per_g, reference = _e1b_clause_rows(config, records)
    if reference is None or reference["median_angle_deg"] is None:
        return {"status": "not_evaluable",
                "reason": "E1b_channel_clean_cell_unavailable",
                "detail": {"cells": per_g}}
    if not reference["seeds_complete"]:
        return {"status": "not_evaluable",
                "reason": (f"E1b_channel_clean_cell_seeds_incomplete_"
                           f"{reference['seeds_recorded']}of"
                           f"{reference['expected_seeds']}"),
                "detail": {"cells": per_g}}
    median = reference["median_angle_deg"]
    return {"status": "pass" if median <= 10.0 else "fail", "reason": None,
            "detail": {"clean_cell_median_angle_deg": median,
                       "threshold_deg": 10.0, "cells": per_g}}


def _r2_e1b_clause(config: dict, records: dict) -> dict:
    if not records:
        return {"status": "not_evaluable",
                "reason": "E1b_pending_v4_R1_R2_clause", "detail": None}
    per_g, _ = _e1b_clause_rows(config, records)
    ordered = [per_g[cell["cell_id"]] for cell in config["E1b"]["cells"]
               if cell["line_multiplier"] == 0.0]
    gammas = [item["g"] for item in ordered]
    means = [item["seed_mean_angle_deg"] for item in ordered]
    if any(value is None for value in means):
        return {"status": "not_evaluable",
                "reason": "E1b_channel_g_sweep_rows_unavailable",
                "detail": {"cells": per_g}}
    if not all(item["seeds_complete"] for item in ordered):
        recorded = sum(item["seeds_recorded"] for item in ordered)
        expected = sum(item["expected_seeds"] for item in ordered)
        return {"status": "not_evaluable",
                "reason": (f"E1b_channel_g_sweep_seeds_incomplete_"
                           f"{recorded}of{expected}"),
                "detail": {"cells": per_g}}
    rho = _spearman(gammas, means)
    at_g = next((item["seed_mean_angle_deg"] for item in ordered
                 if abs(item["g"] - 0.05) < 1e-12), None)
    detail = {"spearman": rho, "seed_mean_angles_deg": means,
              "g_values": gammas, "seed_mean_angle_at_g0p05_deg": at_g,
              "spearman_threshold": R2_SPEARMAN_MIN,
              "at_g0p05_threshold_deg": R2_REQUIRED_ANGLE_DEG}
    if rho is None or at_g is None:
        return {"status": "not_evaluable",
                "reason": "E1b_channel_spearman_unavailable", "detail": detail}
    passed = rho >= R2_SPEARMAN_MIN and at_g >= R2_REQUIRED_ANGLE_DEG
    return {"status": "pass" if passed else "fail", "reason": None,
            "detail": detail}


def _e1a_clause_brief(identifier: str, e1a: dict) -> str:
    """Short, explicit E1a-clause outcome for the pending-clause reason code."""
    status = e1a["status"]
    if status == "pass":
        return "pass"
    if status == "fail":
        cells = e1a.get("cells", {})
        if identifier == "R2":
            passed = sum(1 for cell in cells.values()
                         if cell.get("spearman_pass"))
            return f"fail_{passed}of{len(cells)}_spearman"
        passed = sum(1 for cell in cells.values() if cell.get("pass"))
        return f"fail_{passed}of{len(cells)}_cells"
    return "not_evaluable"


def _combine_v4_clauses(identifier: str, e1a: dict, e1b: dict) -> dict:
    """Combine the v3 E1a clause with the v4 E1b clause (runbook v4 Sec.4).

    While the E1b clause is pending, the reason states what the E1a clause
    already shows so the stored E1a evidence is visible without claiming the
    registered v4 prediction.
    """
    e1a_status = e1a["status"]
    e1b_status = e1b["status"]
    detail = {"e1a": e1a, "e1b": e1b}
    brief = _e1a_clause_brief(identifier, e1a)
    if e1b_status == "not_evaluable":
        e1b_reason = e1b.get("reason") or "E1b_clause_not_evaluable"
        if e1b_reason == "E1b_pending_v4_R1_R2_clause":
            reason = f"E1a_clause_{brief}_{e1b_reason}"
        else:
            reason = f"E1a_clause_{brief}_{e1b_reason}"
        return {"status": "not_evaluable", "reason": reason,
                "seeds": e1a.get("seeds", []), "clauses": detail}
    if e1a_status == "not_evaluable":
        return {"status": "not_evaluable",
                "reason": e1a.get("reason") or "E1a_clause_not_evaluable",
                "seeds": e1a.get("seeds", []), "clauses": detail}
    if "fail" in (e1a_status, e1b_status):
        return {"status": "fail", "reason": None,
                "seeds": e1a.get("seeds", []), "clauses": detail}
    return {"status": "pass", "reason": None,
            "seeds": e1a.get("seeds", []), "clauses": detail}


def compute_r1(config: dict, index) -> dict:
    spec = config["E1a"]
    n = spec["angle_n"]
    seeds = list(spec["seeds"])
    cells = {}
    missing = 0
    for theta, eta in _e1a_scale_cells(config):
        cell = {"theta_scale": theta, "eta_scale": eta, "gamma_load": 0.0, "n": n}
        values = []
        for seed in seeds:
            record = _get(index, cell, seed)
            angle = _method_angle(record, "r1_cca") if record else None
            if angle is None:
                missing += 1
            else:
                values.append(angle)
        median = _median(values)
        if median is None:
            missing += 1
        cells[f"theta{theta:g}_eta{eta:g}"] = {
            "n": n, "gamma_load": 0.0,
            "seeds_recorded": len(values),
            "median_max_angle_deg": median,
            "pass": (None if median is None
                     else median <= R1_MAX_MEDIAN_ANGLE_DEG),
        }
    if missing:
        return {"status": "not_evaluable",
                "reason": f"missing_n{ n }_r1_rows_{missing}",
                "seeds": seeds, "cells": cells}
    passed = all(cell["pass"] for cell in cells.values())
    return {"status": "pass" if passed else "fail", "reason": None,
            "seeds": seeds, "cells": cells}


def compute_r2(config: dict, index) -> dict:
    spec = config["E1a"]
    n = spec["angle_n"]
    seeds = list(spec["seeds"])
    gammas = list(spec["gamma_load"])
    cells = {}
    missing = 0
    for theta, eta in _e1a_scale_cells(config):
        seed_means = []
        for gamma in gammas:
            cell = {"theta_scale": theta, "eta_scale": eta,
                    "gamma_load": gamma, "n": n}
            values = []
            for seed in seeds:
                record = _get(index, cell, seed)
                angle = _method_angle(record, "r1_cca") if record else None
                if angle is None:
                    missing += 1
                else:
                    values.append(angle)
            # v3 §2.4: "Spearman over seed-mean angles" -> the mean across
            # seeds at each gamma level (not the cross-seed median; the two
            # estimators differ, see the E1 independent recompute 2026-10-17).
            seed_means.append(
                statistics.fmean(values) if values else None
            )
        complete = all(value is not None for value in seed_means)
        rho = _spearman(gammas, seed_means) if complete else None
        required_cell = (theta == R2_REQUIRED_CELL[0]
                         and eta == R2_REQUIRED_CELL[1])
        required_angle = None
        required_pass = None
        if required_cell:
            cell = {"theta_scale": theta, "eta_scale": eta,
                    "gamma_load": 1.0, "n": n}
            values = []
            for seed in seeds:
                record = _get(index, cell, seed)
                angle = _method_angle(record, "r1_cca") if record else None
                if angle is not None:
                    values.append(angle)
            required_angle = _median(values)
            required_pass = (None if required_angle is None
                             else required_angle >= R2_REQUIRED_ANGLE_DEG)
        cells[f"theta{theta:g}_eta{eta:g}"] = {
            "seed_mean_angles_deg": seed_means,
            "gamma_loads": gammas,
            "spearman": rho,
            "spearman_pass": None if rho is None else rho >= R2_SPEARMAN_MIN,
            "required_median_at_gamma1_deg": required_angle,
            "required_median_pass": required_pass,
        }
    if missing:
        return {"status": "not_evaluable",
                "reason": f"missing_n{n}_r2_rows_{missing}",
                "seeds": seeds, "cells": cells}
    if any(cell["spearman_pass"] is None for cell in cells.values()):
        return {"status": "not_evaluable", "reason": "unavailable_angle_rows",
                "seeds": seeds, "cells": cells}
    spearman_pass = all(cell["spearman_pass"] for cell in cells.values())
    required = [cell["required_median_pass"] for cell in cells.values()
                if cell["required_median_at_gamma1_deg"] is not None]
    if not required:
        return {"status": "not_evaluable", "reason": "unavailable_required_cell",
                "seeds": seeds, "cells": cells}
    required_pass = all(required)
    return {"status": "pass" if (spearman_pass and required_pass) else "fail",
            "reason": None, "seeds": seeds, "cells": cells}


def compute_r3(config: dict, index) -> dict:
    spec = config["E1a"]
    n = spec["angle_n"]
    seeds = list(spec["seeds"])
    differences = {}
    missing = 0
    numerical_failures = []
    for cell in _e1a_angle_cells(config):
        for seed in seeds:
            record = _get(index, cell, seed)
            test = (record or {}).get("r3_per_view_invariance")
            if test is None:
                missing += 1
                continue
            key = (f"theta{cell['theta_scale']:g}_eta{cell['eta_scale']:g}"
                   f"_g{cell['gamma_load']:g}_s{seed}")
            if test.get("status") == "fail" or test.get(
                    "max_spectrum_difference") is None:
                numerical_failures.append(key)
                continue
            differences[key] = float(test["max_spectrum_difference"])
    detail = {"seeds": seeds, "rows": len(differences),
              "numerical_failures": numerical_failures,
              "max_spectrum_difference": (
                  max(differences.values()) if differences else None),
              "frozen_transform": config["E1a"].get("r3_transform")}
    if missing:
        return {**detail, "status": "not_evaluable",
                "reason": f"missing_n{n}_r3_rows_{missing}"}
    if numerical_failures:
        return {**detail, "status": "not_evaluable",
                "reason": (f"r3_solver_tolerance_failure_"
                           f"{len(numerical_failures)}_of_{len(differences) + len(numerical_failures)}_rows")}
    maximum = max(differences.values()) if differences else None
    return {**detail,
            "status": "pass" if maximum is not None
            and maximum <= R3_MAX_SPECTRUM_DIFFERENCE else "fail",
            "reason": None}



def compute_r3b(config: dict, index) -> dict:
    spec = config["E1a"]
    n = spec["angle_n"]
    seeds = list(spec["seeds"])
    cells = {}
    missing = 0
    for cell in _e1a_angle_cells(config):
        key = (f"theta{cell['theta_scale']:g}_eta{cell['eta_scale']:g}"
               f"_g{cell['gamma_load']:g}")
        entry = {"population_status": None, "population_recovery_rad": None,
                 "median_sample_angle_deg": None, "eligible": False,
                 "pass": None}
        population_statuses = set()
        values = []
        for seed in seeds:
            record = _get(index, cell, seed)
            if record is None:
                missing += 1
                continue
            population = record.get("population") or {}
            oracle = population.get("oracle") or {}
            population_statuses.add(oracle.get("status"))
            entry["population_status"] = oracle.get("status")
            entry["population_recovery_rad"] = oracle.get("recovery_max_angle_rad")
            angle = _method_angle(record, "r9_oracle")
            if angle is not None:
                values.append(angle)
        if population_statuses and population_statuses == {"eligible"}:
            entry["eligible"] = True
            median = _median(values)
            entry["median_sample_angle_deg"] = median
            if (entry["population_recovery_rad"] is None or median is None):
                entry["pass"] = None
            else:
                entry["pass"] = bool(
                    entry["population_recovery_rad"]
                    <= R3B_POPULATION_RECOVERY_RAD
                    and median <= R3B_MAX_MEDIAN_ANGLE_DEG)
        cells[key] = entry
    eligible = {key: value for key, value in cells.items() if value["eligible"]}
    ineligible = [key for key, value in cells.items() if not value["eligible"]]
    annihilation = {
        "fixture": "docs/jepa/reviews/check_p5_counterexample.py",
        "stored_output": "docs/jepa/reviews/P5_COUNTEREXAMPLE_OUTPUT.txt",
        "expected_status": "oracle_rank_ineligible",
        "in_primary_grid": False,
        "reported_rank_ineligibility": (
            "fixture k=1, original target rank 1, conditioned residual rank 0 "
            "(zero whitened cross-view signal); recorded in the stored fixture "
            "output"),
    }
    detail = {"cells": cells, "annihilation_control": annihilation,
              "eligible_cells": len(eligible),
              "ineligible_cells": ineligible, "seeds": seeds}
    if missing:
        return {**detail, "status": "not_evaluable",
                "reason": f"missing_n{n}_r3b_rows_{missing}"}
    if not eligible:
        return {**detail, "status": "not_evaluable",
                "reason": "no_theorem_eligible_cells"}
    if any(value["pass"] is None for value in eligible.values()):
        return {**detail, "status": "not_evaluable",
                "reason": "unavailable_sample_angle_rows"}
    passed = all(value["pass"] for value in eligible.values())
    return {**detail, "status": "pass" if passed else "fail", "reason": None}


def compute_r4a(config: dict, index) -> dict:
    spec = config["E1a"]
    n = spec["angle_n"]
    seeds = list(spec["seeds"])
    cells = {}
    missing = 0
    for cell in _e1a_angle_cells(config):
        key = (f"theta{cell['theta_scale']:g}_eta{cell['eta_scale']:g}"
               f"_g{cell['gamma_load']:g}")
        population_rad = None
        values = []
        for seed in seeds:
            record = _get(index, cell, seed)
            if record is None:
                missing += 1
                continue
            population = record.get("population") or {}
            if population.get("gevp_max_angle_deg") is not None:
                population_rad = math.radians(float(population["gevp_max_angle_deg"]))
            angle = _method_angle(record, "r5_gevp")
            if angle is not None:
                values.append(angle)
        median = _median(values)
        cells[key] = {"population_recovery_rad": population_rad,
                      "median_sample_angle_deg": median,
                      "pass": (None if (population_rad is None or median is None)
                               else bool(population_rad
                                         <= R4_POPULATION_RECOVERY_RAD
                                         and median <= R4_MAX_MEDIAN_ANGLE_DEG))}
    if missing:
        return {"status": "not_evaluable",
                "reason": f"missing_n{n}_r4a_rows_{missing}",
                "seeds": seeds, "cells": cells}
    if any(cell["pass"] is None for cell in cells.values()):
        return {"status": "not_evaluable", "reason": "unavailable_angle_rows",
                "seeds": seeds, "cells": cells}
    passed = all(cell["pass"] for cell in cells.values())
    return {"status": "pass" if passed else "fail", "reason": None,
            "seeds": seeds, "cells": cells}


def compute_r4b(config: dict, index, e1b_aggregate: dict | None) -> dict:
    spec = config["E1a"]
    n = spec["angle_n"]
    seeds = list(spec["seeds"])
    cells = {}
    missing = 0
    for cell in _e1a_angle_cells(config):
        key = (f"theta{cell['theta_scale']:g}_eta{cell['eta_scale']:g}"
               f"_g{cell['gamma_load']:g}")
        records = {}
        for seed in seeds:
            record = _get(index, cell, seed)
            if record is None:
                missing += 1
            else:
                records[seed] = record
        medians = {}
        for method in ("r6_finite_beta_0.1", "r7_finite_beta_1",
                       "r8_finite_beta_10"):
            values = [_method_angle(records[seed], method)
                      for seed in records
                      if _method_angle(records[seed], method) is not None]
            medians[method] = _median(values)
        beta10 = medians["r8_finite_beta_10"]
        cells[key] = {
            "median_angles_deg": medians,
            "pass_beta_10": (None if beta10 is None
                             else beta10 <= R4_MAX_MEDIAN_ANGLE_DEG),
        }
    detail = {"cells": cells, "seeds": seeds,
              "e1b_diagnostic_present": e1b_aggregate is not None}
    if e1b_aggregate is not None:
        detail["e1b_primary_median_angles_deg"] = e1b_aggregate.get(
            "primary_median_angles_deg")
    if missing:
        return {**detail, "status": "not_evaluable",
                "reason": f"missing_n{n}_r4b_rows_{missing}"}
    if any(cell["pass_beta_10"] is None for cell in cells.values()):
        return {**detail, "status": "not_evaluable",
                "reason": "unavailable_beta_10_rows"}
    passed = all(cell["pass_beta_10"] for cell in cells.values())
    return {**detail, "status": "pass" if passed else "fail", "reason": None}


def compute_r5(config: dict, index) -> dict:
    spec = config["E1c"]
    seeds = list(spec["seeds"])
    gammas = list(spec["gamma_load"])
    cells = {}
    missing = 0
    for gamma in gammas:
        records = {}
        for seed in seeds:
            record = _get(index, {"gamma_load": gamma}, seed)
            if record is None or record.get("status") == "not_run":
                missing += 1
                continue
            records[seed] = record
        wins = 0
        evaluable = 0
        per_seed = {}
        for seed, record in records.items():
            depths = record.get("depths") or {}
            first = (depths.get("1") or {}).get("R5") or {}
            third = (depths.get("3") or {}).get("R5") or {}
            entry = {"depth_1_delta": first.get("delta"),
                     "depth_3_delta": third.get("delta"),
                     # dynamics.learning_order reports its top-level state as
                     # status; an evaluable seed needs every mode eligible.
                     "depth_1_eligible": first.get("status") == "eligible",
                     "depth_3_eligible": third.get("status") == "eligible"}
            if (entry["depth_1_eligible"] and entry["depth_3_eligible"]
                    and entry["depth_1_delta"] is not None
                    and entry["depth_3_delta"] is not None):
                evaluable += 1
                win = entry["depth_3_delta"] < entry["depth_1_delta"]
                entry["win"] = bool(win)
                wins += int(win)
            else:
                entry["win"] = None
            per_seed[seed] = entry
        passed = (None if evaluable < R5_MIN_WINS
                  else wins >= R5_MIN_WINS)
        cells[f"gamma{gamma:g}"] = {
            "wins": wins, "evaluable_seeds": evaluable,
            "seeds_recorded": len(records), "per_seed": per_seed,
            "pass": passed}
    if missing:
        return {"status": "not_evaluable",
                "reason": f"missing_e1c_rows_{missing}",
                "seeds": seeds, "cells": cells}
    passed = all(cell["pass"] is True for cell in cells.values())
    if any(cell["pass"] is None for cell in cells.values()):
        return {"status": "not_evaluable", "reason": "seed_evaluable_lt_4",
                "seeds": seeds, "cells": cells}
    return {"status": "pass" if passed else "fail", "reason": None,
            "seeds": seeds, "cells": cells}


def _finite_or_none(value):
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    return value


def _e1a_aggregate(config: dict, records: dict, predictions: dict,
                   root: Path) -> dict:
    spec = config["E1a"]
    counts = {}
    for record in records.values():
        counts[record.get("status", "unknown")] = counts.get(
            record.get("status", "unknown"), 0) + 1
    rows = []
    index = _index(records, "E1a")
    for cell in _e1a_angle_cells(config):
        for seed in spec["seeds"]:
            record = _get(index, cell, seed)
            if record is None:
                continue
            rows.append({
                "cell": cell, "seed": seed, "status": record.get("status"),
                "cca_max_angle_deg": _method_angle(record, "r1_cca"),
                "gevp_max_angle_deg": _method_angle(record, "r5_gevp"),
                "finite_beta_0.1_max_angle_deg": _method_angle(
                    record, "r6_finite_beta_0.1"),
                "finite_beta_1_max_angle_deg": _method_angle(
                    record, "r7_finite_beta_1"),
                "finite_beta_10_max_angle_deg": _method_angle(
                    record, "r8_finite_beta_10"),
                "oracle_max_angle_deg": _method_angle(record, "r9_oracle"),
                "oracle_population_status": (
                    (record.get("population") or {}).get("oracle") or {}
                ).get("status"),
                "r3_max_spectrum_difference": (
                    (record.get("r3_per_view_invariance") or {})
                    .get("max_spectrum_difference")),
            })
    row_table = []
    for theta in spec["theta_scale"]:
        for eta in spec["eta_scale"]:
            for gamma in spec["gamma_load"]:
                for n in spec["n"]:
                    for seed in spec["seeds"]:
                        cell = {"theta_scale": theta, "eta_scale": eta,
                                "gamma_load": gamma, "n": n}
                        record = _get(index, cell, seed)
                        if record is None:
                            continue
                        row_table.append({
                            "cell": cell, "seed": seed,
                            "status": record.get("status"),
                            "reason": record.get("reason"),
                            "cca_max_angle_deg": _method_angle(record, "r1_cca"),
                        })
    attempts = sorted({record.get("_attempt") for record in records.values()
                       if record.get("_attempt")})
    return {
        "campaign": "E1a",
        "config_sha256_note": "row records carry the attempt config hash",
        "provenance": {
            "final_attempt": attempts[-1] if attempts else None,
            "superseded_attempts_archive": "SUPERSEDED_ATTEMPTS_001_006.tar.xz",
            "superseded_attempts_archive_sha256": (
                "2c98e2bc36961807c7bbaab61a116374c53cc62688586c3c1b66c7e399aea1cc"),
            "r3b_implementation_defect": (
                "superseded attempts reported the conditional-oracle row with "
                "angles/probe embeddings measured on the whitened-coordinate "
                "functional instead of the raw pulled-back context map; the "
                "registered definition requires principal angles between row "
                "spaces mapped back to original context coordinates (v3 Sec.4; "
                "P2). Fixed before the final attempt; both runs are archived and "
                "no row was overwritten. R3b is a corrected-implementation "
                "outcome, not a clean first outcome."),
        },
        "angle_n": spec["angle_n"],
        "expected_rows": int(spec["expected_rows"]),
        "recorded_rows": len(records),
        "recorded_by_status": counts,
        "predictions": predictions,
        "angle_n_rows": rows,
        "row_table": row_table,
        "method_equivalence": {
            "r2_hard_isotropy": ("not an independent estimator: the reviewed "
                                 "solver maps beta=0 hard-isotropy prediction "
                                 "and CCA to the same solution; counts as one "
                                 "estimator only"),
            "r1_cca": "independent",
        },
        "negative_control": spec["negative_control"],
    }


def _e1b_aggregate(config: dict, records: dict) -> dict | None:
    if not records:
        return None
    spec = config["E1b"]
    index = _index(records, "E1b")
    cells = {}
    primary = spec["primary_split"]
    primary_medians = {}
    m_diagnostic = None
    for cell_spec in spec["cells"]:
        cell = {"cell_id": cell_spec["cell_id"],
                "common_strength": cell_spec["common_strength"],
                "line_multiplier": cell_spec["line_multiplier"]}
        entry = {"seeds_recorded": 0, "splits": {}}
        for split in spec["splits"]:
            values = {}
            for method in ANGLED:
                values[method] = []
            population = {}
            for seed in spec["seeds"]:
                record = _get(index, cell, seed)
                if record is None:
                    continue
                entry["seeds_recorded"] += 1 if split == primary else 0
                split_record = (record.get("splits") or {}).get(split) or {}
                population = split_record.get("population") or population
                for method in ANGLED:
                    entry_split = (split_record.get("methods") or {}).get(method)
                    if (entry_split and entry_split.get("status") == "evaluated"
                            and entry_split.get("angles")):
                        values[method].append(
                            float(entry_split["angles"]["max_angle_deg"]))
            entry["splits"][split] = {
                "role": ("primary" if split == primary else
                         ("alternative" if split == spec["alternative_split"]
                          else "diagnostic")),
                "median_max_angle_deg": {method: _median(items)
                                         for method, items in values.items()},
                "population": {
                    "gamma_n": population.get("gamma_n"),
                    "displacement_deg": population.get("displacement_deg"),
                    "oracle_status": (population.get("oracle") or {}).get("status"),
                    "cca_max_angle_deg": population.get("cca_max_angle_deg"),
                },
            }
        cells[cell_spec["cell_id"]] = entry
        if primary in entry["splits"]:
            primary_medians[cell_spec["cell_id"]] = entry["splits"][primary][
                "median_max_angle_deg"]
    m_record = records.get("M_development")
    if m_record:
        m_diagnostic = {
            "status": m_record.get("status"),
            "selected_split": m_record.get("selected_split"),
            "scores": m_record.get("scores"),
            "setting": m_record.get("setting"),
            "annotation_only": True,
        }
    return {
        "campaign": "E1b",
        "law": spec["law"],
        "base_rho": spec["base_rho"],
        "theta_sd": spec["theta_sd"],
        "expected_rows": int(spec["expected_rows"]),
        "recorded_rows": len([key for key in records
                              if isinstance(key, str) and key != "M_development"]),
        "primary_split": primary,
        "cells": cells,
        "primary_median_angles_deg": primary_medians,
        "m_diagnostic": m_diagnostic,
        "diagnostic_only": ("E1b angle results are diagnostic extensions; "
                            "no P3 gate at a falsely independent baseline"),
    }


def _e1c_aggregate(config: dict, records: dict) -> dict | None:
    if not records:
        return None
    spec = config["E1c"]
    index = _index(records, "E1c")
    rows = []
    for gamma in spec["gamma_load"]:
        for seed in spec["seeds"]:
            record = _get(index, {"gamma_load": gamma}, seed)
            if record is None:
                continue
            depths = record.get("depths") or {}
            rows.append({
                "gamma_load": gamma, "seed": seed,
                "status": record.get("status"),
                "reason": record.get("reason"),
                "depths": {
                    depth: {
                        "status": (depths.get(str(depth)) or {}).get("status"),
                        "R5": (depths.get(str(depth)) or {}).get("R5"),
                        "completed_steps": (
                            depths.get(str(depth)) or {}).get("completed_steps"),
                    }
                    for depth in spec["depths"]},
            })
    return {"campaign": "E1c", "expected_rows": int(spec["expected_rows"]),
            "recorded_rows": len(records), "rows": rows,
            "provenance": {
                "initialisation": (
                    "dynamics.initialize draws every square encoder layer and "
                    "the predictor as independent Gaussian N(0,(1e-3)^2) "
                    "entries; it does not use the repository init_weights/muP "
                    "zero-init, so v3 Sec.4.2 is implemented as registered"),
                "finding": (
                    "depth-2/3 encoder norms are products of 1e-3-scale layers "
                    "(2.5e-4 and 1.6e-6) and their gradient scale vanishes with "
                    "depth; 100000 steps at lr 1e-3 leave their mode "
                    "contributions at the initialisation floor, so R5 modes are "
                    "censored. This is a registered-protocol consequence; no "
                    "hyperparameter was changed and E1c was not re-run."),
            }}


def build_predictions(root: Path, config_path: Path) -> tuple[list[dict], dict]:
    """Return (prediction rows for PREDICTIONS.md, aggregate table dict)."""
    config, _ = runner.load_config(config_path)
    status_path = root / "docs" / "jepa" / "PREDICTION_STATUS.json"
    status = json.loads(status_path.read_text(encoding="utf-8"))
    status_rows = {row["id"]: dict(row) for row in status["predictions"]}
    order = [row["id"] for row in status["predictions"]]

    e1a_records, e1a_dir = _e1a_records(root)
    e1b_records, e1b_dir = _e1b_records(root)
    e1c_records, e1c_dir = _e1c_records(root)
    e1a_index = _index(e1a_records, "E1a")
    e1c_index = _index(e1c_records, "E1c")

    aggregates = {}
    e1b_aggregate = _e1b_aggregate(config, e1b_records)
    if e1b_aggregate is not None:
        aggregates["E1b"] = e1b_aggregate
    e1c_aggregate = _e1c_aggregate(config, e1c_records)
    if e1c_aggregate is not None:
        aggregates["E1c"] = e1c_aggregate

    computed: dict[str, dict] = {}
    if e1a_records:
        r1 = _combine_v4_clauses("R1", compute_r1(config, e1a_index),
                                 _r1_e1b_clause(config, e1b_records))
        r2 = _combine_v4_clauses("R2", compute_r2(config, e1a_index),
                                 _r2_e1b_clause(config, e1b_records))
        r3 = compute_r3(config, e1a_index)
        r3b = compute_r3b(config, e1a_index)
        r4a = compute_r4a(config, e1a_index)
        r4b = compute_r4b(config, e1a_index, e1b_aggregate)
        predictions = {"R1": r1, "R2": r2, "R3": r3, "R3b": r3b,
                       "R4a": r4a, "R4b": r4b}
        aggregate = _e1a_aggregate(config, e1a_records, predictions, root)
        aggregates["E1a"] = aggregate
        for identifier, detail in predictions.items():
            final = detail["status"] in ("pass", "fail")
            evidence = None
            if final:
                evidence = (_evidence_path(root, e1a_dir / "aggregate_E1a.json")
                            + "; " + _prediction_summary(identifier, detail))
                if identifier == "R3b":
                    evidence += ("; corrected-implementation outcome "
                                 "(oracle pullback fix; superseded attempts "
                                 "archived)")
                if identifier == "R4b" and e1b_aggregate is not None:
                    evidence += ("; E1b diagnostics "
                                 + _evidence_path(root,
                                                  e1b_dir / "aggregate_E1b.json"))
            computed[identifier] = {
                "id": identifier, "campaign": "E1",
                "status": detail["status"],
                "reason": detail.get("reason") or "evaluated_from_stored_tables",
                "seeds": list(detail.get("seeds", [])),
                "evidence": evidence}
    if e1c_records:
        r5 = compute_r5(config, e1c_index)
        if "E1c" not in aggregates:
            aggregates["E1c"] = _e1c_aggregate(config, e1c_records)
        final = r5["status"] in ("pass", "fail")
        computed["R5"] = {
            "id": "R5", "campaign": "E1", "status": r5["status"],
            "reason": r5.get("reason") or "evaluated_from_stored_tables",
            "seeds": list(r5.get("seeds", [])),
            "evidence": ((_evidence_path(root, e1c_dir / "aggregate_E1c.json")
                          + "; " + _prediction_summary("R5", r5))
                         if final else None)}
        aggregates["E1c"]["predictions"] = {"R5": r5}
    elif e1a_records:
        computed["R5"] = {
            "id": "R5", "campaign": "E1", "status": "not_run",
            "reason": "E1c_not_run", "seeds": [], "evidence": None}
    for identifier in ("R1", "R2", "R3", "R3b", "R4a", "R4b"):
        if identifier not in computed and e1c_records:
            computed[identifier] = {
                "id": identifier, "campaign": "E1", "status": "not_run",
                "reason": "E1a_not_run", "seeds": [], "evidence": None}

    rows = []
    for identifier in order:
        if identifier in computed:
            rows.append(computed[identifier])
        else:
            rows.append(status_rows[identifier])
    for identifier in computed:
        if identifier not in status_rows:
            raise ValueError(f"computed prediction {identifier} is not registered")
    return rows, aggregates


