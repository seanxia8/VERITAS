# --------------------------------------------------------------------- gate
def _section_zero(text: str) -> str:
    start = text.find("## 0.")
    if start < 0:
        start = text.find("## 0 ")
    if start < 0:
        return ""
    end = text.find("\n## ", start + 3)
    return text[start: end if end >= 0 else None]


def assert_authorised(root=None) -> dict:
    """Hard gate (§0): full author line + H4 row in runbook §0, line in DECISIONS."""
    root = Path(root) if root is not None else Path(__file__).resolve().parents[2]
    runbook, decisions = root / RUNBOOK_REL, root / DECISIONS_REL
    problems = []
    if not runbook.is_file() or not decisions.is_file():
        problems.append(f"missing {runbook} or {decisions}")
    else:
        section = _section_zero(runbook.read_text())
        if AUTHOR_LINE not in section:
            problems.append(f"{RUNBOOK_REL} §0 does not contain {AUTHOR_LINE!r}")
        if H4_ROW not in section:
            problems.append(f"{RUNBOOK_REL} §0 does not contain the H4 row")
        if "NOT AUTHORISED" in section:
            problems.append(f"{RUNBOOK_REL} §0 still carries a NOT AUTHORISED banner")
        if AUTHOR_LINE not in decisions.read_text():
            problems.append(f"{DECISIONS_REL} does not contain {AUTHOR_LINE!r}")
    if problems:
        for problem in problems:
            print(f"[arch] authorisation gate: {problem}", file=sys.stderr)
        raise SystemExit(2)
    return {"authorised": True, "runbook": str(runbook),
            "runbook_sha256": lr.sha256_file(runbook), "decisions": str(decisions),
            "author_line": AUTHOR_LINE, "h4_row": H4_ROW}


# ------------------------------------------------------------ variant wrapper
def variant_config(variant: str) -> pe.EncoderConfig:
    """``dataclasses.replace(EncoderConfig(), **VARIANTS[variant])``."""
    if variant not in VARIANTS:
        raise ValueError(f"unknown variant {variant!r}; expected one of {sorted(VARIANTS)}")
    return dataclasses.replace(pe.EncoderConfig(), **VARIANTS[variant])


def encoder_signature(encoder_config) -> dict:
    config = encoder_config or pe.EncoderConfig()
    return {"window": int(config.window), "shift": int(config.shift),
            "n_pred_blocks": int(config.n_pred_blocks),
            "default_window": DEFAULT_ENCODER[0], "default_shift": DEFAULT_ENCODER[1]}


@contextlib.contextmanager
def build_arm_patch(variant: str, log=print):
    """Process-level wrapper on ``lucid_run.build_arm`` injecting the variant config.

    ``run_one`` and ``er.item_arm`` call ``lr.build_arm`` without ``encoder_config``,
    so the wrapper supplies the variant's ``EncoderConfig`` in that case and passes
    an explicitly supplied config through unchanged.  Restored in a ``finally``.
    """
    if variant not in VARIANTS:
        raise ValueError(f"unknown variant {variant!r}")
    override = variant_config(variant)
    original = lr.build_arm

    def build(arm_name, geometry, arms_config, cell, seed, beta=None, dark_bank=None,
              encoder_config=None):
        if encoder_config is None:
            encoder_config = override
        made = original(arm_name, geometry, arms_config, cell, seed, beta=beta,
                        dark_bank=dark_bank, encoder_config=encoder_config)
        log(f"[arch] build_arm wrapper: variant={variant} "
            f"window={encoder_config.window} shift={encoder_config.shift} "
            f"n_pred_blocks={encoder_config.n_pred_blocks}")
        return made

    lr.build_arm = build
    try:
        yield
    finally:
        lr.build_arm = original


# ---------------------------------------------------------------- preflight
def live_free_entries(guard_json=GUARD_JSON) -> dict:
    guard_json = Path(guard_json)
    if not guard_json.is_file():
        raise RuntimeError(f"guard status {guard_json} is missing; cannot check entries")
    status = json.loads(guard_json.read_text())
    free = (status.get("caps") or {}).get("free_entries")
    if free is None:
        raise RuntimeError(f"{guard_json}: guard status has no caps.free_entries")
    return {"free_entries": int(free), "guard_level": status.get("level"),
            "guard_reasons": status.get("reasons"),
            "guard_timestamp": status.get("timestamp"), "guard_json": str(guard_json)}


def entries_projection(free_before: int, *, clone: int = ENTRIES_CLONE,
                       suite: int = ENTRIES_SUITE, extension: int = ENTRIES_EXT,
                       floor: int = ENTRIES_FLOOR) -> dict:
    projected = int(free_before) - (int(clone) + int(suite) + int(extension))
    return {"free_before": int(free_before), "clone": int(clone), "suite": int(suite),
            "extension": int(extension), "projected_after": int(projected),
            "floor": int(floor),
            "pass": bool(projected >= int(floor) and int(free_before) >= int(floor))}


def probe_status(data_root) -> dict:
    """Read-only dev-cohort/probe-set check; nothing is ever regenerated here."""
    root = Path(data_root) / "lucid"
    out = {"data_root": str(data_root), "sets": {}}
    for key, expected in PROBE_MANIFESTS.items():
        manifest = root / key / "manifest.json"
        row = {"manifest": str(manifest), "exists": manifest.is_file(),
               "expected_sha256": expected}
        if manifest.is_file():
            row["manifest_sha256"] = lr.sha256_file(manifest)
            row["pass"] = row["manifest_sha256"] == expected
        else:
            row["manifest_sha256"] = None
            row["pass"] = False
        out["sets"][key] = row
    out["pass"] = all(row["pass"] for row in out["sets"].values())
    return out


def require_data(config, gen, geometry, data_root, *, code_sha=None, log=print):
    """Verify (never regenerate) the committed dev cohort + probe sets, then load."""
    status = probe_status(data_root)
    if not status["pass"]:
        raise SystemExit(f"[arch] probe-set preflight failed (never regenerate): {status}")
    preflight = eh.preflight_data(Path(data_root))
    if not preflight.get("pass"):
        raise SystemExit(f"[arch] dev data preflight failed: {preflight}")
    cell = lr.dev_cell(config)
    train_ds, probes = eh.datasets_for(cell, config, gen, geometry, Path(data_root),
                                       code_sha=code_sha)
    return train_ds, probes, {"probes": status, "preflight": preflight}


# ----------------------------------------------------------------- run dirs
def run_id_for(seed) -> str:
    return lr.run_id_for(CELL_ID, ARM_NAME, int(seed))


def out_root_for(ext_root, variant) -> Path:
    return Path(ext_root) / "train" / "arch" / variant


def run_dir_for(ext_root, variant, seed) -> Path:
    return out_root_for(ext_root, variant) / "runs" / run_id_for(seed)


def sidecar_payload(variant, seed, out_root, steps, device) -> dict:
    return {"registered": False, "extension": EXTENSION, "variant": variant,
            "seed": int(seed), "arm": ARM_NAME, "cell_id": CELL_ID,
            "out_root": str(out_root), "run_id": run_id_for(seed),
            "steps": int(steps), "device": str(device)}


def prepare_run_dir(out_root, variant, seed, *, steps=STEPS, device=None) -> tuple:
    """Refuse an existing run directory and write the per-run sidecar (§2)."""
    if variant not in VARIANTS:
        raise ValueError(f"unknown variant {variant!r}")
    run_id, run_dir = run_id_for(seed), Path(out_root) / "runs" / run_id_for(seed)
    if run_dir.exists():
        raise RuntimeError(f"{run_dir} already exists; refusing to launch (run_one would "
                           f"auto-resume it). Archive or remove it first.")
    run_dir.mkdir(parents=True, exist_ok=False)
    (run_dir / "variant.json").write_text(json.dumps(
        sidecar_payload(variant, seed, Path(out_root), steps, device), indent=1) + "\n")
    return run_id, run_dir


def summarize_run(run_dir, *, variant, seed, wall_seconds=None, steps=None,
                  resumed_from_step=0, forms=None) -> dict:
    run_dir = Path(run_dir)
    check = eh.train_log_check(run_dir)
    checkpoint = run_dir / "final.pt"
    status = json.loads((run_dir / "run_status.json").read_text()) \
        if (run_dir / "run_status.json").is_file() else {}
    return {"registered": False, "extension": EXTENSION, "variant": variant,
            "seed": int(seed), "run_id": run_dir.name, "arm": ARM_NAME,
            "cell_id": CELL_ID, "steps_scheduled": steps,
            "steps_completed": status.get("steps_completed"),
            "resumed_from_step": int(resumed_from_step),
            "status": status.get("outcome"),
            "final_train_metrics": check.get("final_metrics"),
            "non_finite_keys": check.get("non_finite_keys"),
            "metrics_finite": check.get("finite"),
            "final_checkpoint_sha256": (lr.sha256_file(checkpoint)
                                        if checkpoint.is_file() else None),
            "wall_seconds": wall_seconds, "forms": forms}


# ----------------------------------------------------------------- training
def run_one_training(*, variant, seed, ext_root, config, gen, arms_config, geometry,
                     device, data_root, config_path, code_sha, status_text,
                     steps=None, probe_max_events=None, out_root=None, log=print) -> dict:
    """The exact ``run_one`` call of runbook §3.1 with the variant wrapper installed."""
    gate = assert_authorised()
    train_ds, probes, data_info = require_data(config, gen, geometry, data_root,
                                               code_sha=code_sha, log=log)
    scheduled = int(STEPS if steps is None else steps)
    launch_root = Path(out_root) if out_root is not None else out_root_for(ext_root, variant)
    run_id, run_dir = prepare_run_dir(launch_root, variant, seed, steps=scheduled,
                                      device=device)
    started = __import__("time").time()
    with build_arm_patch(variant, log=log):
        result = lr.run_one(
            arm_name=ARM_NAME, cell=lr.dev_cell(config), seed=int(seed), beta=None,
            config=config, arms_config=arms_config, geometry=geometry,
            loader_dataset=train_ds, probe_datasets=probes, dark_bank=None,
            out_root=launch_root, data_root=Path(data_root),
            config_sha=lr.sha256_file(config_path), code_sha=code_sha,
            status_text=status_text, device=device, steps=None if steps is None else steps,
            micro_batch=None, resume=None, stop_after=None, checkpoint_minutes=None,
            evaluate=False, allow_pending=False, step_callback=None,
            probe_max_events=probe_max_events, save_embeddings=False,
            physics_method="ridge", tf32=False, log=log)
    from . import ext_h1clean as ec
    resumed = ec.assert_fresh_resume(result["training"], run_id)
    summary = summarize_run(run_dir, variant=variant, seed=seed,
                            wall_seconds=round(__import__("time").time() - started, 3),
                            steps=scheduled, resumed_from_step=resumed)
    summary["smoke"] = scheduled == 20
    summary["encoder"] = encoder_signature(variant_config(variant))
    summary["probes_preflight"] = {"pass": data_info["preflight"].get("pass")}
    (run_dir / "ext_summary.json").write_text(json.dumps(summary, indent=1,
                                                         default=float) + "\n")
    return {"result": result, "run_dir": run_dir, "summary": summary,
            "run_id": run_id, "seed": int(seed), "variant": variant, "gate": gate}


# --------------------------------------------------------------- evaluation
def read_variant(run_dir, variant=None) -> str:
    """Variant from ``--variant`` or the run's ``variant.json`` sidecar."""
    if variant is not None:
        if variant not in VARIANTS:
            raise SystemExit(f"[arch] unknown variant {variant!r}")
        return variant
    sidecar = Path(run_dir) / "variant.json"
    if not sidecar.is_file():
        raise SystemExit(f"[arch] {sidecar} missing; pass --variant explicitly")
    payload = json.loads(sidecar.read_text())
    found = payload.get("variant")
    if found not in VARIANTS:
        raise SystemExit(f"[arch] {sidecar}: unknown variant {found!r}")
    return found


def evaluate_run_dirs(variant, run_dirs, probes, geometry, config, arms_config, *,
                      device, max_events=None) -> dict:
    runs = {}
    with build_arm_patch(variant, log=print):
        for run_dir in run_dirs:
            run_dir = Path(run_dir)
            if run_dir.name == "runs" or (run_dir / "runs").is_dir():
                candidates = sorted((run_dir / "runs").glob("*"))
            else:
                candidates = [run_dir]
            for candidate in candidates:
                sidecar_path = candidate / "variant.json"
                if not sidecar_path.is_file():
                    raise SystemExit(f"[arch] {sidecar_path} missing")
                sidecar = json.loads(sidecar_path.read_text())
                if sidecar.get("variant") != variant:
                    raise SystemExit(f"[arch] {sidecar_path}: variant "
                                     f"{sidecar.get('variant')!r} != {variant!r}")
                seed = int(sidecar["seed"])
                source = candidate / "final.pt"
                if not source.is_file():
                    raise SystemExit(f"[arch] {candidate}: final.pt is missing")
                item = {"label": f"arch_{variant}_{seed}", "arm": ARM_NAME,
                        "split": "within", "seed": seed, "beta": None,
                        "source": str(source)}
                metrics = eh.evaluate_run(item, probes, geometry, config, arms_config,
                                          device=device, max_events=max_events)
                runs[str(seed)] = {
                    "variant": variant, "seed": seed, "run_id": candidate.name,
                    "run_dir": str(candidate), "variant_config": VARIANTS[variant],
                    "encoder": encoder_signature(variant_config(variant)),
                    "checkpoint_sha256": lr.sha256_file(source),
                    "full_input": metrics["forms"]["full_input"],
                    "half_pass": metrics["forms"]["half_pass"],
                    "ext_summary": (json.loads((candidate / "ext_summary.json").read_text())
                                    if (candidate / "ext_summary.json").is_file() else None)}
    return runs


def write_variants_json(ext_root, run_dirs) -> dict:
    variants = {"registered": False, "extension": EXTENSION, "runs": {}}
    for run_dir in run_dirs:
        run_dir = Path(run_dir)
        candidates = sorted((run_dir / "runs").glob("*")) if (run_dir / "runs").is_dir() else [run_dir]
        for candidate in candidates:
            sidecar_path = candidate / "variant.json"
            if sidecar_path.is_file():
                variants["runs"][str(candidate)] = json.loads(sidecar_path.read_text())
    path = Path(ext_root) / "variants.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    if path.is_file():
        existing = json.loads(path.read_text())
        variants["runs"] = dict(existing.get("runs") or {}, **variants["runs"])
    tmp.write_text(json.dumps(variants, indent=1, default=float) + "\n")
    os.replace(tmp, path)
    return variants


# ------------------------------------------------------- reading arch_r §2
def arch_r(variant_runs: dict, *, full_floor=INIT_FULL_VERTEX_M,
           half_floor=INIT_HALF_VERTEX_M, charge_min=CHARGE_R2_MIN,
           init_full=None, init_half=None) -> dict:
    """Per-variant two-sided ``arch_r`` over the same rows as ``eh.recover`` (§2)."""
    full_rows = {seed: run["full_input"] for seed, run in variant_runs.items()}
    half_rows = {seed: run["half_pass"] for seed, run in variant_runs.items()}
    recovered = eh.recover(full_rows, half_rows, init_full or {}, init_half or {})
    rows = {}
    for seed, row in recovered["seeds"].items():
        full_v, full_r2 = row["full_input_vertex_m"], row["full_input_token_r2"]
        half_v, half_r2 = row["half_pass_vertex_m"], row["half_pass_token_r2"]
        recovers = bool(full_v is not None and float(full_v) < float(full_floor)
                        and full_r2 is not None and float(full_r2) >= float(charge_min)
                        and half_v is not None and float(half_v) < float(half_floor)
                        and half_r2 is not None and float(half_r2) >= float(charge_min))
        fails = bool((full_v is not None and float(full_v) >= float(full_floor))
                     or full_r2 is None or float(full_r2) < float(charge_min))
        rows[str(seed)] = {"full_input_vertex_m": full_v,
                           "full_input_token_r2": full_r2,
                           "half_pass_vertex_m": half_v,
                           "half_pass_token_r2": half_r2,
                           "recovers": recovers, "fails": fails}
    values = list(rows.values())
    if values and all(row["recovers"] for row in values):
        verdict = "recovered"
        direction = "recovered: the collapse is not architecture-robust for this knob"
    elif values and all(row["fails"] for row in values):
        verdict = "not recovered"
        direction = "not recovered: the collapse survives this architecture/masking change"
    else:
        verdict = "unclear"
        direction = "unclear (partial recovery, seed disagreement or half-pass contradiction)"
    return {"registered": False, "extension": EXTENSION,
            "criteria": {"floors": {"full": float(full_floor),
                                    "half": float(half_floor), "charge_r2_min": float(charge_min)},
                         "rule": "recovered: both seeds full vertex strictly < %.6f m, full "
                                 "token ln q R2 >= %.1f, half vertex < %.6f m, half token "
                                 "R2 >= %.1f; not recovered: for each seed full vertex >= "
                                 "%.6f m or full token R2 < %.1f (both seeds); else unclear"
                                 % (full_floor, charge_min, half_floor, charge_min,
                                    full_floor, charge_min)},
            "verdict": verdict, "direction": direction, "per_seed": rows}
