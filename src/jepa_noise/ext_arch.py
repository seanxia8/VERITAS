"""Architecture/masking control extension (extension, ``registered: false``).

Runbook: ``docs/jepa/RUNBOOK_2026-11-02_ARCH.md`` (2 Nov 2026, reviewed, authorised).
Extension name: ``arch_2026-11-02``.

Six ``sigreg_jepa`` runs (10 000 steps, seeds 9000/9001) on the committed 100k
development cohort, varying one architecture/masking knob at a time through a
process-level ``lucid_run.build_arm`` wrapper that injects an ``EncoderConfig``:

* ``window128``: ``window=128, shift=64``
* ``window32``:  ``window=32, shift=16``
* ``pred4``:    ``n_pred_blocks=4``

The wrapper is also installed for evaluation (the readout rebuilds arms via
``lr.build_arm`` without ``encoder_config``, so ``pred4`` would otherwise fail its
strict checkpoint load and the window variants would be evaluated at the default
window).  Each variant has its own out root because the run id is identical across
variants.

This module holds the gate, ``VARIANTS``, the wrapper, the entries preflight, thin
training/evaluation helpers, the sidecars, and the per-variant ``arch_r`` reading.
"""
